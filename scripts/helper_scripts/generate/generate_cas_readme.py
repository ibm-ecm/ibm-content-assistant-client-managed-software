"""
Module for generating a README.md inside the generatedFiles/<namespace>/ folder
produced by the 'generate' mode of the IBM Content Assistant Prerequisites CLI.

The README is built dynamically from the properties that were used during
generation, so it accurately reflects exactly which files were created and what
each file contains.
"""

import os
from datetime import datetime
from pathlib import Path
from typing import Optional
from logging import Logger


class GenerateCASReadme:
    """
    Generate a README.md file inside the generatedFiles/<namespace>/ folder.

    The README is assembled from the same property dictionaries that drove
    secret and CR generation, so it is always in sync with the actual output.
    """

    def __init__(
        self,
        namespace: str,
        content_assistant_properties: dict = None,
        vector_database_properties: dict = None,
        deployment_properties: dict = None,
        ingress_properties: dict = None,
        trusted_certs_present: bool = False,
        opensearch_generated: bool = False,
        logger: Optional[Logger] = None,
    ):
        self._logger = logger
        self._namespace = namespace
        self._ca_props = content_assistant_properties or {}
        self._vdb_props = vector_database_properties or {}
        self._deploy_props = deployment_properties or {}
        self._ingress_props = ingress_properties or {}
        self._trusted_certs_present = trusted_certs_present
        self._opensearch_generated = opensearch_generated

        self._generated_folder = Path.cwd() / "generatedFiles" / namespace
        self._readme_path = self._generated_folder / "README.md"

    # ── internal helpers ──────────────────────────────────────────────────────

    def _log(self, message: str) -> None:
        if self._logger:
            self._logger.info(message)

    def _write(self, content: str) -> bool:
        try:
            with open(self._readme_path, "w", encoding="utf-8") as f:
                f.write(content)
            self._log(f"Generated README: {self._readme_path}")
            return True
        except Exception as e:
            if self._logger:
                self._logger.error(f"Failed to write README: {e}")
            return False

    # ── section builders ──────────────────────────────────────────────────────

    def _header(self) -> str:
        ts = datetime.now().strftime("%Y-%m-%d %H:%M")
        license_model = self._deploy_props.get("LICENSE", "").upper() or "N/A"
        platform = self._deploy_props.get("PLATFORM", "N/A")
        cas_version = self._deploy_props.get("CAS_VERSION", "N/A")
        return (
            f"# Generated Files — IBM Content Assistant\n\n"
            f"> Auto-generated by `prerequisites.py generate` on **{ts}**\n>\n"
            f"> **Namespace:** `{self._namespace}`  \n"
            f"> **License model:** `{license_model}`  \n"
            f"> **Platform:** `{platform}`  \n"
            f"> **CAS version:** `{cas_version}`\n\n"
            f"This folder contains all Kubernetes artifacts needed to deploy IBM Content Assistant.\n"
            f"Apply them to your cluster in the order shown in the [Deployment Order](#deployment-order) section.\n\n"
            f"---\n\n"
        )

    def _folder_tree(self) -> str:
        lines = [
            "## Folder Structure\n",
            "```",
            f"generatedFiles/{self._namespace}/",
            "├── README.md                              ← this file",
            "├── ibm_content_assistant_cr.yaml          ← CASCluster Custom Resource",
            "├── secrets/",
            "│   ├── ibm-content-assistant-secret.yaml  ← AI provider credentials",
        ]

        # vector database secrets
        vdb_ids = self._vdb_props.get("_vector_database_ids", [])
        for idx, vdb_id in enumerate(vdb_ids):
            db_num = "" if idx == 0 else f"-{idx + 1}"
            lines.append(f"│   └── vector-database{db_num}-secret.yaml     ← vector DB credentials")
            vdb = self._vdb_props.get(vdb_id, {})
            if vdb.get("DATABASE_SSL_ENABLED"):
                cert_name = "vector-database-certificate-secret" if idx == 0 else f"vector_database-{idx + 1}-certificate-secret"
                lines.append(f"│       (+ ssl/{cert_name}.yaml)")
                if vdb.get("DATABASE_AUTH_TYPE", "").lower() == "oidc":
                    oidc_name = "vector-database-oidc-certificate-secret" if idx == 0 else f"vector_database-{idx + 1}-oidc-certificate-secret"
                    lines.append(f"│       (+ ssl/{oidc_name}.yaml)")

        lines.append("├── ssl/")
        lines.append("│   ├── ibm-content-assistant-admin-key-secret.yaml  ← admin RSA key pair")

        # AI provider SSL secrets
        ai_provider_ids = self._ca_props.get("_ai_providers_ids", [])
        for idx, ai_id in enumerate(ai_provider_ids):
            if self._ca_props.get(ai_id, {}).get("SSL_ENABLED"):
                num_suffix = "" if idx == 0 else f"-{idx + 1}"
                lines.append(f"│   ├── ai-provider{num_suffix}-certificate-secret.yaml")

        if self._trusted_certs_present:
            lines.append("│   └── trusted-certs/")
            lines.append("│       └── trusted-cert-N-secret.yaml          ← additional trust anchors")

        if self._opensearch_generated:
            lines.append("├── opensearch/")
            lines.append("│   ├── opensearch_admin_secret.yaml")
            lines.append("│   ├── opensearch_genai_secret.yaml")
            lines.append("│   ├── opensearch_route.yaml")
            lines.append("│   ├── opensearch_cluster.yaml")
            lines.append("│   ├── opensearch_cluster_permission_job.yaml")
            lines.append("│   └── README.md")

        lines.append("└── metrics/                                   ← reserved for future use")
        lines.append("```\n")
        return "\n".join(lines) + "\n---\n\n"

    def _cr_section(self) -> str:
        license_model = self._deploy_props.get("LICENSE", "").lower()
        platform = self._deploy_props.get("PLATFORM", "N/A")
        storage = self._deploy_props.get("SLOW_FILE_STORAGE_CLASSNAME", "N/A")
        network_policies = self._deploy_props.get("GENERATE_NETWORK_POLICIES", False)

        # Collect trusted certs list from ssl folder if present
        ssl_folder = self._generated_folder / "ssl"
        trusted_list = []
        if ssl_folder.exists():
            for f in sorted(ssl_folder.iterdir()):
                name = f.stem
                if "ai-provider" in name or "trusted-cert" in name:
                    trusted_list.append(name)

        trusted_display = ", ".join(f"`{n}`" for n in trusted_list) if trusted_list else "_none_"

        ingress_line = ""
        if self._ingress_props:
            hostname = self._ingress_props.get("INGRESS_HOSTNAME", "N/A")
            ingress_line = f"| `spec.shared_configuration.sc_deployment_hostname_suffix` | Ingress hostname suffix: `{hostname}` |\n"

        egress_line = ""
        if platform == "other" and network_policies:
            egress_line = "| `spec.shared_configuration.sc_egress_configuration` | Egress rules for k8s API and DNS |\n"

        return (
            "## `ibm_content_assistant_cr.yaml`\n\n"
            "The `CASCluster` Custom Resource consumed by the IBM Content Assistant operator.\n\n"
            "| Field | Value / Description |\n"
            "|---|---|\n"
            f"| `spec.shared_configuration.sc_cas_license_type` | `{license_model}` |\n"
            f"| `spec.shared_configuration.sc_deployment_platform` | `{platform}` |\n"
            f"| `spec.shared_configuration.sc_generate_sample_network_policies` | `{str(network_policies).lower()}` |\n"
            f"| `spec.shared_configuration.storage_configuration.sc_slow_file_storage_classname` | `{storage}` |\n"
            f"| `spec.shared_configuration.trusted_certificate_list` | {trusted_display} |\n"
            + ingress_line
            + egress_line
            + "| `spec.vector_database` | See [Vector Database Secrets](#secrets) below |\n\n"
            "---\n\n"
        )

    def _secrets_section(self) -> str:
        lines = ["## Secrets\n"]

        # ── Content Assistant secret ──────────────────────────────────────────
        lines.append("### `secrets/ibm-content-assistant-secret.yaml`\n")
        lines.append("Credentials for each configured AI provider.  ")
        lines.append("All values are **base64-encoded** in the `data` block.\n")
        lines.append("| Key | Description |")
        lines.append("|---|---|")

        ai_provider_ids = self._ca_props.get("_ai_providers_ids", [])
        for ai_id in ai_provider_ids:
            provider = self._ca_props.get(ai_id, {})
            label = provider.get("AI_PROVIDER_LABEL", ai_id).upper()
            lines.append(f"| `AI_PROVIDER_API_KEY_{label}` | API key for AI provider `{label}` |")
            if "SPACE_ID" in provider:
                lines.append(f"| `AI_PROVIDER_SPACE_ID_{label}` | watsonx.ai SaaS Space ID |")
            elif "USERNAME" in provider:
                lines.append(f"| `AI_PROVIDER_USERNAME_{label}` | watsonx.ai Lightweight username |")

        if "MODELGATEWAY" in self._ca_props:
            lines.append("| `AI_PROVIDER_API_KEY_MODELGATEWAY` | API key for ModelGateway |")

        lines.append("")

        # ── Vector database secret(s) ─────────────────────────────────────────
        vdb_ids = self._vdb_props.get("_vector_database_ids", [])
        for idx, vdb_id in enumerate(vdb_ids):
            vdb = self._vdb_props.get(vdb_id, {})
            db_num = "" if idx == 0 else f"-{idx + 1}"
            secret_name = f"vector-database{db_num}-secret"
            auth_type = vdb.get("DATABASE_AUTH_TYPE", "BASICAUTH").upper()
            db_url = vdb.get("DATABASE_URL", "N/A")
            ssl_enabled = vdb.get("DATABASE_SSL_ENABLED", False)

            lines.append(f"### `secrets/{secret_name}.yaml`\n")
            lines.append(f"Credentials for vector database `{vdb_id}` at `{db_url}`.  ")
            lines.append(f"Authentication type: **{auth_type}** | SSL: **{str(ssl_enabled).lower()}**\n")
            lines.append("| Key | Description |")
            lines.append("|---|---|")
            lines.append("| `VECTOR_DATABASE_USER_ID` | Database username |")
            lines.append("| `VECTOR_DATABASE_USER_PASSWORD` | Database password |")
            if auth_type == "OIDC":
                lines.append("| `VECTOR_DATABASE_OIDC_TOKEN_ENDPOINT` | OIDC token endpoint URL |")
                lines.append("| `VECTOR_DATABASE_OIDC_CLIENT_ID` | OIDC client ID |")
                lines.append("| `VECTOR_DATABASE_OIDC_CLIENT_SECRET` | OIDC client secret |")
            lines.append("")

        lines.append("---\n")
        return "\n".join(lines) + "\n"

    def _ssl_section(self) -> str:
        lines = ["## SSL Secrets\n"]

        # ── Admin key secret ──────────────────────────────────────────────────
        lines.append("### `ssl/ibm-content-assistant-admin-key-secret.yaml`\n")
        lines.append(
            "Auto-generated RSA-2048 key pair used for Content Assistant internal token authentication.  \n"
            "A new key is generated on every `generate` run. **Do not edit manually.**\n"
        )
        lines.append("| Key | Description |")
        lines.append("|---|---|")
        lines.append("| `admin_key.pem` | PKCS8 encrypted RSA private key |")
        lines.append("| `ACCESS_TOKEN_KEY_PASSPHRASE` | Passphrase for the encrypted key |\n")

        # ── AI provider SSL secrets ───────────────────────────────────────────
        ai_provider_ids = self._ca_props.get("_ai_providers_ids", [])
        for idx, ai_id in enumerate(ai_provider_ids):
            provider = self._ca_props.get(ai_id, {})
            if provider.get("SSL_ENABLED"):
                num_suffix = "" if idx == 0 else f"-{idx + 1}"
                secret_name = f"ai-provider{num_suffix}-certificate-secret"
                label = provider.get("AI_PROVIDER_LABEL", ai_id)
                lines.append(f"### `ssl/{secret_name}.yaml`\n")
                lines.append(
                    f"TLS certificate used to trust the `{label}` AI provider endpoint.  \n"
                    f"Sourced from `propertyFile/{self._namespace}/ssl-certs/ai-provider{num_suffix}/`.\n"
                )
                lines.append("| Key | Description |")
                lines.append("|---|---|")
                lines.append("| `tls.crt` | PEM certificate chain (base64-encoded) |\n")

        # ── Vector database SSL secrets ───────────────────────────────────────
        vdb_ids = self._vdb_props.get("_vector_database_ids", [])
        for idx, vdb_id in enumerate(vdb_ids):
            vdb = self._vdb_props.get(vdb_id, {})
            if vdb.get("DATABASE_SSL_ENABLED"):
                cert_name = "vector-database-certificate-secret" if idx == 0 else f"vector_database-{idx + 1}-certificate-secret"
                db_url = vdb.get("DATABASE_URL", "N/A")
                lines.append(f"### `ssl/{cert_name}.yaml`\n")
                lines.append(
                    f"TLS certificate used to trust the vector database at `{db_url}`.  \n"
                    f"Sourced from `propertyFile/{self._namespace}/ssl-certs/{vdb_id.lower()}/`.\n"
                )
                lines.append("| Key | Description |")
                lines.append("|---|---|")
                lines.append("| `tls.crt` | PEM certificate chain (base64-encoded) |\n")

                if vdb.get("DATABASE_AUTH_TYPE", "").lower() == "oidc":
                    oidc_name = "vector-database-oidc-certificate-secret" if idx == 0 else f"vector_database-{idx + 1}-oidc-certificate-secret"
                    lines.append(f"### `ssl/{oidc_name}.yaml`\n")
                    lines.append(
                        f"TLS certificate for the OIDC endpoint of vector database `{vdb_id}`.  \n"
                        f"Sourced from `propertyFile/{self._namespace}/ssl-certs/{vdb_id.lower()}-oidc/`.\n"
                    )
                    lines.append("| Key | Description |")
                    lines.append("|---|---|")
                    lines.append("| `tls.crt` | PEM certificate chain (base64-encoded) |\n")

        # ── Trusted certs ─────────────────────────────────────────────────────
        if self._trusted_certs_present:
            lines.append("### `ssl/trusted-certs/trusted-cert-N-secret.yaml`\n")
            lines.append(
                "One secret per certificate file found in "
                f"`propertyFile/{self._namespace}/ssl-certs/trusted-certs/`.  \n"
                "These are added to the CR's `trusted_certificate_list`.\n"
            )
            lines.append("| Key | Description |")
            lines.append("|---|---|")
            lines.append("| `tls.crt` | PEM certificate chain (base64-encoded) |\n")

        lines.append("---\n")
        return "\n".join(lines) + "\n"

    def _opensearch_section(self) -> str:
        if not self._opensearch_generated:
            return ""

        cluster_hostname = self._deploy_props.get("OPENSEARCH_CLUSTER_HOSTNAME", "N/A")
        vdb_ids = self._vdb_props.get("_vector_database_ids", [])
        vdb_url = "N/A"
        if vdb_ids:
            vdb_url = self._vdb_props.get(vdb_ids[0], {}).get("DATABASE_URL", "N/A")

        return (
            "## OpenSearch Cluster (CP4BA)\n\n"
            "These files are generated only when the **CP4BA** license model is selected and the "
            "OpenSearch cluster creation option was enabled during `gather`.\n\n"
            f"> Cluster external hostname: `{cluster_hostname}`  \n"
            f"> Vector database URL in CR: `{vdb_url}`\n\n"
            "| File | Purpose |\n"
            "|---|---|\n"
            "| `opensearch_admin_secret.yaml` | Admin credentials for the cluster (`ica-opensearch-admin-user-secret`) |\n"
            "| `opensearch_genai_secret.yaml` | GenAI service-user credentials (`ica-opensearch-genai-secret`) |\n"
            "| `opensearch_route.yaml` | cert-manager `Certificate` that provisions `ica-opensearch-tls-secret` |\n"
            "| `opensearch_cluster.yaml` | `opensearch.cloudpackopen.ibm.com/v1` Cluster resource |\n"
            "| `opensearch_cluster_permission_job.yaml` | Bootstrap Job — creates roles and the `genai-service-user` account |\n\n"
            "> See `opensearch/README.md` for the full step-by-step apply order.\n\n"
            "---\n\n"
        )

    def _deployment_order(self) -> str:
        lines = [
            "## Deployment Order\n",
            "Apply files in this sequence to satisfy dependencies:\n",
            "```bash",
            f"NAMESPACE={self._namespace}\n",
            "# 1. Secrets",
            f"kubectl apply -n $NAMESPACE -f {self._namespace}/secrets/ibm-content-assistant-secret.yaml",
        ]

        vdb_ids = self._vdb_props.get("_vector_database_ids", [])
        for idx, _ in enumerate(vdb_ids):
            db_num = "" if idx == 0 else f"-{idx + 1}"
            lines.append(f"kubectl apply -n $NAMESPACE -f {self._namespace}/secrets/vector-database{db_num}-secret.yaml")

        has_ssl = False
        ai_provider_ids = self._ca_props.get("_ai_providers_ids", [])
        for idx, ai_id in enumerate(ai_provider_ids):
            if self._ca_props.get(ai_id, {}).get("SSL_ENABLED"):
                has_ssl = True
                break
        for idx, vdb_id in enumerate(vdb_ids):
            if self._vdb_props.get(vdb_id, {}).get("DATABASE_SSL_ENABLED"):
                has_ssl = True
                break
        if has_ssl or self._trusted_certs_present:
            lines.append("")
            lines.append("# 2. SSL / certificate secrets")
            lines.append(f"kubectl apply -n $NAMESPACE -f {self._namespace}/ssl/")

        if self._opensearch_generated:
            lines += [
                "",
                "# 3. OpenSearch cluster (wait for healthy before the job)",
                f"kubectl apply -n $NAMESPACE -f {self._namespace}/opensearch/opensearch_admin_secret.yaml",
                f"kubectl apply -n $NAMESPACE -f {self._namespace}/opensearch/opensearch_genai_secret.yaml",
                f"kubectl apply -n $NAMESPACE -f {self._namespace}/opensearch/opensearch_route.yaml",
                f"kubectl apply -n $NAMESPACE -f {self._namespace}/opensearch/opensearch_cluster.yaml",
                f"kubectl wait --for=condition=Ready cluster/ica-opensearch -n $NAMESPACE --timeout=600s",
                f"kubectl apply -n $NAMESPACE -f {self._namespace}/opensearch/opensearch_cluster_permission_job.yaml",
            ]
            cr_step = "4"
        elif has_ssl or self._trusted_certs_present:
            cr_step = "3"
        else:
            cr_step = "2"

        lines += [
            "",
            f"# {cr_step}. Custom Resource",
            f"kubectl apply -n $NAMESPACE -f {self._namespace}/ibm_content_assistant_cr.yaml",
            "```\n",
        ]
        return "\n".join(lines) + "\n---\n\n"

    def _notes(self) -> str:
        return (
            "## Notes\n\n"
            "- All secrets use `type: Opaque` with **base64-encoded** `data` values. "
            "Do not edit them by hand — re-run `generate` to regenerate from updated property files.\n"
            "- Secrets labelled `cas.ibm.com/backup-type: mandatory` must be included in cluster backups.\n"
            "- Re-running `generate` archives the previous output to `backups/generatedFiles_"
            f"{self._namespace}_<timestamp>.zip` before replacing it.\n"
            "- The `metrics/` folder is reserved for future use and may be empty.\n"
        )

    # ── public entry point ────────────────────────────────────────────────────

    def generate_readme(self) -> bool:
        """
        Build and write README.md to the generatedFiles/<namespace>/ folder.

        Returns:
            True if the file was written successfully, False otherwise.
        """
        content = (
            self._header()
            + self._folder_tree()
            + self._cr_section()
            + self._secrets_section()
            + self._ssl_section()
            + self._opensearch_section()
            + self._deployment_order()
            + self._notes()
        )
        return self._write(content)
