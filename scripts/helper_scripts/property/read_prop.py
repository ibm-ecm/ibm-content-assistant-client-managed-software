class CASAIProviderConfig(BaseModel):
    """Validates a single [AI_PROVIDER*] section in cas_properties.toml."""

    model_config = {"extra": "allow"}   # tolerate unknown/future keys

    AI_PROVIDER_LABEL: str = Field(..., min_length=1)
    URL: str = Field(..., min_length=1)
    API_KEY: str = Field(..., min_length=1)

    # Optional — SaaS providers supply SPACE_ID or PROJECT_ID
    SPACE_ID: Optional[str] = Field(None)
    PROJECT_ID: Optional[str] = Field(None)
    # Optional — Lightweight Engine providers
    USERNAME: Optional[str] = Field(None)
    SSL_ENABLED: Optional[bool] = Field(None)

    @field_validator("URL")
    @classmethod
    def _url_valid(cls, v: str) -> str:
        if v == "<Required>":
            raise ValueError("URL must be set — replace the <Required> placeholder")
        if not v.startswith(("http://", "https://")):
            raise ValueError("URL must start with http:// or https://")
        return v

    @field_validator("API_KEY")
    @classmethod
    def _api_key_not_placeholder(cls, v: str) -> str:
        if v == "<Required>":
            raise ValueError("API_KEY must be set — replace the <Required> placeholder")
        return v


