class _VDBAuthType(str, Enum):
    BASICAUTH = "BASICAUTH"
    OIDC = "OIDC"
    APIKEY = "APIKEY"


class CASVectorDatabaseConfig(BaseModel):
    """Validates a single [VECTORDB*] section in cas_vector_database.toml."""

    model_config = {"extra": "allow"}   # tolerate unknown/future keys

    DATABASE_URL: str = Field(..., min_length=1)
    DATABASE_AUTH_TYPE: _VDBAuthType
    DATABASE_SSL_ENABLED: bool = Field(True)
    DATABASE_USERNAME: str = Field(..., min_length=1)
    DATABASE_USER_PASSWORD: str = Field(..., min_length=1)

    DATABASE_TYPE: Optional[str] = Field(None)
    DATABASE_OIDC_ENDPOINT: Optional[str] = Field(None)
    DATABASE_OIDC_CLIENT_ID: Optional[str] = Field(None)
    DATABASE_OIDC_CLIENT_SECRET: Optional[str] = Field(None)

    @field_validator("DATABASE_URL")
    @classmethod
    def _db_url_valid(cls, v: str) -> str:
        if v == "<Required>":
            raise ValueError("DATABASE_URL must be set — replace the <Required> placeholder")
        if not v.startswith(("http://", "https://")):
            raise ValueError("DATABASE_URL must start with http:// or https://")
        return v

    @field_validator("DATABASE_USER_PASSWORD")
    @classmethod
    def _password_not_placeholder(cls, v: str) -> str:
        if v == "<Required>":
            raise ValueError(
                "DATABASE_USER_PASSWORD must be set — replace the <Required> placeholder"
            )
        return v

    @model_validator(mode="after")
    def _oidc_fields_required(self) -> "CASVectorDatabaseConfig":
        if self.DATABASE_AUTH_TYPE == _VDBAuthType.OIDC:
            missing = [
                f for f in (
                    "DATABASE_OIDC_ENDPOINT",
                    "DATABASE_OIDC_CLIENT_ID",
                    "DATABASE_OIDC_CLIENT_SECRET",
                )
                if not getattr(self, f)
            ]
            if missing:
                raise ValueError(f"OIDC auth requires: {', '.join(missing)}")
        return self


# ─────────────────────────────────────────────────────────────────────────────
# Helper — strip pydantic's "Value error, " prefix from messages
# ─────────────────────────────────────────────────────────────────────────────

def _clean_msg(msg: str) -> str:
    return msg[len("Value error, "):] if msg.startswith("Value error, ") else msg


# ─────────────────────────────────────────────────────────────────────────────
# Base ReadProp class (unchanged from original)
# ─────────────────────────────────────────────────────────────────────────────

class ReadProp():
    # Recursively checks for missing/required fields
    # in tables or tables within tables
    def __recurse_check_values(self, table, key_history=[]):
        for key in table:
            # If the value is indicated as another table,
            # we recursively call this function to check for other tables
            if type(table[key]) is dict:
                # key_history is required when outputting which specific
                # field is missing to the user when using recursive calls
                self.__recurse_check_values(table[key], key_history + [key])

            elif type(table[key]) is list:
                if "<Required>" in table[key]:
                    # Create a new entry for this property file as to what fields might be
                    # split filename from path and store it in required_fields
                    if platform.system() == "Windows":
                        delimiter = "\\"
                    else:
                        delimiter = "/"
                    file_name = self._prop_filepath.split(delimiter + "propertyFile" + delimiter)[-1]

                    if file_name not in self.required_fields:
                        self.required_fields[file_name] = []
                    self.required_fields[file_name].append((key_history + [key], table[key]))

            # If the value field is not a table, we just check
            # the user has not entered or edited the fields yet
            elif table[key] == '<Required>' or table[key] == '':
                # Create a new entry for this property file as to what fields might be
                # split filename from path and store it in required_fields
                if platform.system() == "Windows":
                    delimiter = "\\"
                else:
                    delimiter = "/"
                file_name = self._prop_filepath.split(delimiter + "propertyFile" + delimiter)[-1]

                if file_name not in self.required_fields:
                    self.required_fields[file_name] = []
                self.required_fields[file_name].append((key_history + [key], table[key]))

    # Returns true if user has missed any required fields.
    def missing_required_fields(self):
        if len(self.required_fields) > 0:
            return True
        return False

    # function to read property files into dictionaries
    def __init__(self, propertyfile, logger):
        self._prop_filepath = None
        # Instance-level dict — each ReadProp object tracks only its own file's issues
        self.required_fields = {}

        self._logger = logger
        self._prop_filepath = propertyfile
        self._toml_dict = None
        self._toml_dict = toml.loads(open(self._prop_filepath, encoding="utf-8").read())
        self.__recurse_check_values(self._toml_dict)


    def to_dict(self):
        return self._toml_dict


# ─────────────────────────────────────────────────────────────────────────────
# CAS-specific subclasses — add pydantic validation on top of base scan
# ─────────────────────────────────────────────────────────────────────────────

def _file_key(prop_filepath: str) -> str:
    """Return the path fragment after 'propertyFile/' for use as required_fields key."""
    delimiter = "\\" if platform.system() == "Windows" else "/"
    return prop_filepath.split(delimiter + "propertyFile" + delimiter)[-1]


def _replace_section_errors(
    required_fields: Dict[str, List],
    file_name: str,
    section_ids: set,
    model_class: type,
    sections: Dict[str, Any],
    logger,
) -> None:
    """
    Run pydantic validation for each section in *section_ids* and replace the
    generic ``<Required>`` placeholder entries (produced by the base class scan)
    with precise pydantic error messages.

    This ensures every field is reported exactly **once** with the best
    description available.
    """
    # Drop the generic placeholder entries for these sections — pydantic
    # will repopulate with better messages.
    if file_name in required_fields:
        required_fields[file_name] = [
            entry for entry in required_fields[file_name]
            if not (
                isinstance(entry[0], (list, tuple))
                and entry[0]
                and str(entry[0][0]) in section_ids
            )
        ]
        if not required_fields[file_name]:
            del required_fields[file_name]

    for section_id in section_ids:
        section = sections.get(section_id, {})
        if not isinstance(section, dict):
            continue
        try:
            model_class(**section)
        except ValidationError as exc:
            for e in exc.errors():
                loc = [section_id] + list(e["loc"])
                msg = _clean_msg(e["msg"])
                if file_name not in required_fields:
                    required_fields[file_name] = []
                required_fields[file_name].append((loc, msg))
            logger.debug(
                "Pydantic validation for %s in %s: %s", section_id, file_name, exc
            )


# ReadPropContentAssistant — pydantic-validated AI provider sections
class ReadPropContentAssistant(ReadProp):
    def __find_ai_providers_ids(self):
        # Filter for keys that start with "AI_PROVIDER"
        # and add them to the list of AI provider IDs
        ai_providers_ids = [key for key in self._toml_dict.keys() if key.startswith("AI_PROVIDER")]
        self._toml_dict["_ai_providers_ids"] = ai_providers_ids
        self._toml_dict["ai_providers_number"] = len(ai_providers_ids)

    def __init__(self, propertyfile, logger):
        super().__init__(propertyfile, logger)
        self.__find_ai_providers_ids()
        file_name = _file_key(self._prop_filepath)
        # Pydantic pass — replaces generic placeholder entries with precise messages
        _replace_section_errors(
            required_fields=self.required_fields,
            file_name=file_name,
            section_ids=set(self._toml_dict.get("_ai_providers_ids", [])),
            model_class=CASAIProviderConfig,
            sections=self._toml_dict,
            logger=self._logger,
        )
        # Validate [MODELGATEWAY] section if present
        if "MODELGATEWAY" in self._toml_dict:
            _replace_section_errors(
                required_fields=self.required_fields,
                file_name=file_name,
                section_ids={"MODELGATEWAY"},
                model_class=CASModelGatewayConfig,
                sections=self._toml_dict,
                logger=self._logger,
            )


